package com.takima.backskeleton.services;

import com.takima.backskeleton.DAO.RestaurantDao;
import com.takima.backskeleton.DAO.ReviewDao;
import com.takima.backskeleton.DTO.RestaurantDto;
import com.takima.backskeleton.DTO.RestaurantMapper;
import com.takima.backskeleton.DTO.RestaurantRankingDto;
import com.takima.backskeleton.models.Restaurant;
import com.takima.backskeleton.models.Review;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
public class RestaurantService {

    private final RestaurantDao restaurantDao;
    private final ReviewDao reviewDao;

    public RestaurantService(
            RestaurantDao restaurantDao,
            ReviewDao reviewDao
    ) {
        this.restaurantDao = restaurantDao;
        this.reviewDao = reviewDao;
    }

    // Get all restaurants with calculated rating statistics.
    public List<RestaurantDto> getAllRestaurants() {
        return restaurantDao.findAll()
                .stream()
                .map(this::toDtoWithRating)
                .toList();
    }

    // Get one restaurant with calculated rating statistics.
    public RestaurantDto getRestaurantById(Long id) {
        Restaurant restaurant = restaurantDao.findById(id)
                .orElseThrow(() -> new ResponseStatusException(
                        HttpStatus.NOT_FOUND,
                        "Restaurant not found: " + id
                ));

        return toDtoWithRating(restaurant);
    }

    /**
     * Ranking added on main.
     * Uses the aggregate query already defined in ReviewDao.
     */
    public List<RestaurantRankingDto> getRestaurantRanking() {
        return reviewDao.findRestaurantRanking()
                .stream()
                .map(row -> new RestaurantRankingDto(
                        ((Number) row[0]).longValue(),
                        (String) row[1],
                        ((Number) row[2]).doubleValue(),
                        ((Number) row[3]).longValue()
                ))
                .toList();
    }

    // Create a restaurant.
    @Transactional
    public RestaurantDto createRestaurant(RestaurantDto dto) {
        validateRestaurant(dto);

        Restaurant restaurant =
                RestaurantMapper.fromDto(dto, null);

        // ID is generated by PostgreSQL.
        restaurant.setId(null);

        Restaurant saved =
                restaurantDao.save(restaurant);

        return toDtoWithRating(saved);
    }

    // Edit a restaurant.
    @Transactional
    public RestaurantDto updateRestaurant(
            Long id,
            RestaurantDto dto
    ) {
        validateRestaurant(dto);

        Restaurant existing =
                restaurantDao.findById(id)
                        .orElseThrow(
                                () -> new ResponseStatusException(
                                        HttpStatus.NOT_FOUND,
                                        "Restaurant not found: " + id
                                )
                        );

        existing.setTitle(dto.getTitle().trim());
        existing.setAddress(dto.getAddress());
        existing.setOpeningHours(dto.getOpeningHours());
        existing.setImageUrl(dto.getImageUrl());
        existing.setCuisine(dto.getCuisine());

        Restaurant saved =
                restaurantDao.save(existing);

        return toDtoWithRating(saved);
    }

    // Delete a restaurant.
    @Transactional
    public void deleteRestaurant(Long id) {
        Restaurant existing =
                restaurantDao.findById(id)
                        .orElseThrow(
                                () -> new ResponseStatusException(
                                        HttpStatus.NOT_FOUND,
                                        "Restaurant not found: " + id
                                )
                        );

        restaurantDao.delete(existing);
    }

    /**
     * Converts a restaurant into a DTO and calculates its current
     * average rating and number of reviews.
     *
     * These values are derived from reviews instead of being duplicated
     * in the restaurants table.
     */
    private RestaurantDto toDtoWithRating(
            Restaurant restaurant
    ) {
        RestaurantDto dto =
                RestaurantMapper.toDto(restaurant);

        List<Review> reviews =
                reviewDao
                        .findByRestaurantIdOrderByCreatedAtDesc(
                                restaurant.getId()
                        );

        long reviewCount = reviews.size();

        double averageRating =
                reviews.stream()
                        .mapToInt(Review::getRating)
                        .average()
                        .orElse(0.0);

        // Keep one decimal place.
        averageRating =
                Math.round(averageRating * 10.0) / 10.0;

        dto.setAverageRating(averageRating);
        dto.setReviewCount(reviewCount);

        return dto;
    }

    private void validateRestaurant(
            RestaurantDto dto
    ) {
        if (dto == null
                || dto.getTitle() == null
                || dto.getTitle().trim().isEmpty()) {

            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST,
                    "Restaurant title is required"
            );
        }
    }
}